def _patch_stopline_writer_z():
    orig_create = _SLNode.create_node

    def create_with_z(sl):
        """Create a stop line node with <z> in <point>."""
        node = orig_create(sl)  # use original method gernerate <stopLine> + two <point> + other nodes

        # collect the <point> children and their indices
        children = list(node)  # keep the order of children
        point_idx = [i for i, ch in enumerate(children) if ch.tag == "point"]

        def _mk_point(arr):
            if arr is None:
                return None
            x = float(arr[0]); y = float(arr[1])
            if len(arr) >= 3:
                z = float(arr[2])
                return _Point(x, y, z).create_node()
            else:
                return _Point(x, y).create_node()

        # replece the first point
        if hasattr(sl, "start"):
            new_start = _mk_point(sl.start)
            if new_start is not None:
                if len(point_idx) >= 1:
                    i0 = point_idx[0]
                    node.remove(children[i0])
                    node.insert(i0, new_start)
                else:
                    # extreme situation: no point generated by original function
                    node.insert(0, new_start)

        # replace second point and update children/point_idx
        children = list(node)
        point_idx = [i for i, ch in enumerate(children) if ch.tag == "point"]
        if hasattr(sl, "end"):
            new_end = _mk_point(sl.end)
            if new_end is not None:
                if len(point_idx) >= 2:
                    i1 = point_idx[1]
                    node.remove(children[i1])
                    node.insert(i1, new_end)
                else:
                    # if there's no second point,follow the first point or append directly
                    if len(point_idx) == 1:
                        node.insert(point_idx[0] + 1, new_end)
                    else:
                        node.append(new_end)

        return node

    _SLNode.create_node = staticmethod(create_with_z)

