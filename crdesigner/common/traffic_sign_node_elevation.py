from lxml import etree 
def _patch_sign_writer():
    orig_create = _TSNode.create_node
    def create_with_z(ts):
        node = orig_create(ts)
        pos = getattr(ts, "position", None)
        if pos is not None and len(pos) == 3:
            x, y, z = map(float, pos)
            pos_node = node.find("position")
            if pos_node is not None:
                old_pt = pos_node.find("point")
                new_pt = _Point(x, y, z).create_node()
                if old_pt is not None:
                    pos_node.remove(old_pt)
                pos_node.append(new_pt)
        return node
    _TSNode.create_node = staticmethod(create_with_z)

